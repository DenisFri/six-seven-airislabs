#!/usr/bin/env python3
"""Airis Core handover validation. Runs on the bastion.

Postgres is reached only through `kubectl port-forward`, the one approved path: the node has
no public IP and every Service is ClusterIP-only. Exit code 1 if any check fails.
"""
import argparse
import base64
import json
import logging
import socket
import subprocess
import sys
import time
import uuid
from contextlib import contextmanager
from datetime import datetime, timezone
from urllib.parse import urlparse

import psycopg

HEALTHY = "Cluster in healthy state"
log = logging.getLogger("validate")


def kubectl(*args, timeout=60):
    """Run kubectl and return stdout. A non-zero exit raises, which fails the calling check."""
    done = subprocess.run(["kubectl", *args], capture_output=True, text=True, timeout=timeout)
    if done.returncode:
        raise RuntimeError(done.stderr.strip().splitlines()[-1] if done.stderr.strip() else "kubectl failed")
    return done.stdout.strip()


def kubectl_json(*args):
    return json.loads(kubectl(*args, "-o", "json"))


def check(name, fn):
    """A check returns one line of evidence, or raises. A failure never aborts the run."""
    try:
        passed, evidence = True, fn()
    except Exception as exc:  # noqa: BLE001  any error is a failed check, not a crash
        passed, evidence = False, f"{type(exc).__name__}: {exc}"[:300]
    log.info("%s  %-36s %s", "PASS" if passed else "FAIL", name, evidence)
    return {"name": name, "passed": passed, "evidence": evidence}


# ---- Kubernetes layer ---------------------------------------------------------------------

def node_ip():
    """The address the bastion dials for the API is the node's private IP (Step 9 sed)."""
    server = kubectl("config", "view", "--minify", "-o", "jsonpath={.clusters[0].cluster.server}")
    host = urlparse(server).hostname
    if host in (None, "127.0.0.1", "localhost"):
        raise RuntimeError(f"kubeconfig points at {server!r}; it must use the node's private IP")
    return host


def api_server():
    host = node_ip()
    if kubectl("get", "--raw", "/readyz") != "ok":
        raise RuntimeError("API server /readyz did not answer ok")
    return f"https://{host}:6443 readyz=ok"


def nodes_ready():
    nodes = kubectl_json("get", "nodes")["items"]
    ready = [n["metadata"]["name"] for n in nodes
             if any(c["type"] == "Ready" and c["status"] == "True" for c in n["status"]["conditions"])]
    if not nodes or len(ready) != len(nodes):
        raise RuntimeError(f"{len(ready)}/{len(nodes)} nodes Ready")
    return f"{len(ready)}/{len(nodes)} Ready: {', '.join(ready)}"


def operator_available():
    deploys = kubectl_json("-n", "cnpg-system", "get", "deploy")["items"]
    available = [d["metadata"]["name"] for d in deploys if d["status"].get("availableReplicas", 0)]
    if not available:
        raise RuntimeError("no available deployment in cnpg-system")
    return f"available: {', '.join(available)}"


def cluster_status(ns, name):
    st = kubectl_json("-n", ns, "get", "cluster", name).get("status", {})
    summary = (f"phase={st.get('phase')!r} ready={st.get('readyInstances')}/{st.get('instances')} "
               f"primary={st.get('currentPrimary')}")
    if st.get("phase") != HEALTHY or st.get("readyInstances") != st.get("instances") or not st.get("currentPrimary"):
        raise RuntimeError(summary)
    return summary


# ---- Postgres layer, through the tunnel ---------------------------------------------------

def credentials(ns, cluster):
    """Generated by the operator into a Secret. Held in memory, never logged, never in the report."""
    data = kubectl_json("-n", ns, "get", "secret", f"{cluster}-app")["data"]
    decoded = {k: base64.b64decode(v).decode() for k, v in data.items()}
    return {"user": decoded["username"], "password": decoded["password"], "dbname": decoded.get("dbname", "app")}


@contextmanager
def port_forward(ns, service, local_port):
    proc = subprocess.Popen(["kubectl", "-n", ns, "port-forward", f"svc/{service}", f"{local_port}:5432"],
                            stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    try:
        deadline = time.monotonic() + 20
        while True:
            try:
                socket.create_connection(("127.0.0.1", local_port), timeout=1).close()
                break
            except OSError:
                if time.monotonic() > deadline or proc.poll() is not None:
                    raise RuntimeError(f"port-forward to svc/{service} did not come up")
                time.sleep(0.5)
        yield
    finally:
        proc.terminate()
        proc.wait(timeout=10)


def round_trip(conn):
    token = uuid.uuid4().hex
    conn.execute("CREATE TABLE IF NOT EXISTS handover_probe (token text, at timestamptz DEFAULT now())")
    conn.execute("INSERT INTO handover_probe (token) VALUES (%s)", (token,))
    row = conn.execute("SELECT token FROM handover_probe WHERE token = %s", (token,)).fetchone()
    conn.execute("DROP TABLE handover_probe")
    if row is None or row[0] != token:
        raise RuntimeError("inserted row did not come back")
    return f"insert + select of token {token[:8]}... on the primary, scratch table dropped"


def replication(conn, expected):
    n = conn.execute("SELECT count(*) FROM pg_stat_replication").fetchone()[0]
    if n < expected:
        raise RuntimeError(f"{n} standby connected, expected at least {expected}")
    return f"{n} standby streaming from the primary (expected >= {expected})"


def tls(conn):
    ssl, version = conn.execute("SELECT ssl, version FROM pg_stat_ssl WHERE pid = pg_backend_pid()").fetchone()
    if not ssl:
        raise RuntimeError("this session is not encrypted")
    return f"session encrypted with {version}"


# ---- Negative tests: what must NOT work ---------------------------------------------------

def no_external_ip():
    addrs = kubectl("get", "nodes", "-o", 'jsonpath={.items[*].status.addresses[?(@.type=="ExternalIP")].address}')
    if addrs:
        raise RuntimeError(f"a node advertises an ExternalIP: {addrs}")
    return "no node advertises an ExternalIP"


def direct_port_closed(host, port=5432):
    try:
        socket.create_connection((host, port), timeout=3).close()
    except OSError as exc:
        return f"{host}:{port} not reachable from the bastion ({type(exc).__name__}: {exc})"
    raise RuntimeError(f"{host}:{port} accepted a direct TCP connection")


def no_exposed_services():
    svcs = kubectl_json("get", "svc", "-A")["items"]
    exposed = [f"{s['metadata']['namespace']}/{s['metadata']['name']}={s['spec']['type']}"
               for s in svcs if s["spec"]["type"] in ("NodePort", "LoadBalancer")]
    if exposed:
        raise RuntimeError(", ".join(exposed))
    return f"{len(svcs)} services, none of type NodePort or LoadBalancer"


def chaos_failover(ns, name, timeout=180):
    old = kubectl_json("-n", ns, "get", "cluster", name)["status"]["currentPrimary"]
    kubectl("-n", ns, "delete", "pod", old, "--wait=false")
    start = time.monotonic()
    while time.monotonic() - start < timeout:
        st = kubectl_json("-n", ns, "get", "cluster", name).get("status", {})
        if (st.get("currentPrimary") != old and st.get("phase") == HEALTHY
                and st.get("readyInstances") == st.get("instances")):
            return f"deleted {old}; {st['currentPrimary']} promoted, cluster healthy again after {time.monotonic() - start:.0f}s"
        time.sleep(2)
    raise RuntimeError(f"no healthy cluster with a new primary within {timeout}s")


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--namespace", default="airis-core")
    p.add_argument("--cluster", default="airis-core")
    p.add_argument("--local-port", type=int, default=15432, help="bastion-side port of the port-forward")
    p.add_argument("--report", default="handover_report.json")
    p.add_argument("--chaos", action="store_true", help="delete the primary pod and time the failover")
    args = p.parse_args()
    logging.basicConfig(level=logging.INFO, format="%(message)s")
    ns, name = args.namespace, args.cluster

    results = [
        check("Kubernetes API on the private IP", api_server),
        check("Node Ready", nodes_ready),
        check("CNPG operator available", operator_available),
        check("Cluster healthy", lambda: cluster_status(ns, name)),
    ]

    db_checks = [("Write/read round trip", round_trip),
                 ("Streaming replication", lambda c: replication(c, expected)),
                 ("TLS on the connection", tls)]
    try:
        expected = kubectl_json("-n", ns, "get", "cluster", name)["spec"]["instances"] - 1
        creds = credentials(ns, name)
        with port_forward(ns, f"{name}-rw", args.local_port), psycopg.connect(
                host="127.0.0.1", port=args.local_port, sslmode="require", connect_timeout=10,
                autocommit=True, **creds) as conn:
            results += [check(n, lambda: fn(conn)) for n, fn in db_checks]
    except Exception as exc:  # noqa: BLE001  no tunnel or no login: every DB check fails
        log.info("FAIL  database checks: %s", exc)
        results += [{"name": n, "passed": False, "evidence": f"{type(exc).__name__}: {exc}"[:300]} for n, _ in db_checks]

    results += [
        check("Negative: node has no ExternalIP", no_external_ip),
        check("Negative: direct 5432 to the node", lambda: direct_port_closed(node_ip())),
        check("Negative: no NodePort/LoadBalancer", no_exposed_services),
    ]
    if args.chaos:
        results.append(check("Chaos: delete primary, time failover", lambda: chaos_failover(ns, name)))

    passed = sum(r["passed"] for r in results)
    report = {"timestamp": datetime.now(timezone.utc).isoformat(timespec="seconds"),
              "cluster": f"{ns}/{name}", "passed": passed, "failed": len(results) - passed, "checks": results}
    with open(args.report, "w", encoding="utf-8") as fh:
        json.dump(report, fh, indent=2)
    log.info("\n%d/%d checks passed. Report: %s", passed, len(results), args.report)
    sys.exit(0 if passed == len(results) else 1)


if __name__ == "__main__":
    main()
